import argparse
import csv
import random
from pathlib import Path

import cv2
import numpy as np

"""
Python script generated by GitHub Co-Pilot to take the video recordings of myself holding waste items and
split them into individual frames. Uses laplacian variance to check for blur and checks images for 
similarity to avoid duplicates. Organises each class of videos into train, test, val folders as required
to train the model.

"""

VIDEO_EXTS = {".mp4", ".mov", ".m4v", ".avi", ".mkv"}


def is_video_file(path: Path) -> bool:
    return path.suffix.lower() in VIDEO_EXTS


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def laplacian_variance(image: np.ndarray) -> float:
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    return cv2.Laplacian(gray, cv2.CV_64F).var()


def make_thumb(image: np.ndarray, size=(32, 32)) -> np.ndarray:
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)
    return cv2.resize(gray, size, interpolation=cv2.INTER_AREA)


def mean_abs_diff(a: np.ndarray, b: np.ndarray) -> float:
    return float(np.mean(np.abs(a.astype(np.float32) - b.astype(np.float32))))


def resize_if_needed(image: np.ndarray, max_side: int | None) -> np.ndarray:
    if max_side is None or max_side <= 0:
        return image

    h, w = image.shape[:2]
    longest = max(h, w)
    if longest <= max_side:
        return image

    scale = max_side / longest
    new_w = max(1, int(w * scale))
    new_h = max(1, int(h * scale))
    return cv2.resize(image, (new_w, new_h), interpolation=cv2.INTER_AREA)


def split_videos(video_paths, train_ratio=0.7, val_ratio=0.15, seed=42):
    """
    Split videos within a single class.

    Rules:
    - 1 video: train
    - 2 videos: train, test
    - 3 videos: train, val, test
    - 4+ videos: approximate ratios, but ensure at least 1 val and 1 test
    """
    videos = list(video_paths)
    rng = random.Random(seed)
    rng.shuffle(videos)
    n = len(videos)

    if n == 0:
        return [], [], []
    if n == 1:
        return videos, [], []
    if n == 2:
        return [videos[0]], [], [videos[1]]
    if n == 3:
        return [videos[0]], [videos[1]], [videos[2]]

    n_train = max(1, int(round(n * train_ratio)))
    n_val = max(1, int(round(n * val_ratio)))
    n_test = n - n_train - n_val

    if n_test < 1:
        n_test = 1
        if n_train > n_val and n_train > 1:
            n_train -= 1
        elif n_val > 1:
            n_val -= 1

    while n_train + n_val + n_test > n:
        if n_train > 1:
            n_train -= 1
        elif n_val > 1:
            n_val -= 1
        else:
            break

    while n_train + n_val + n_test < n:
        n_train += 1

    train = videos[:n_train]
    val = videos[n_train:n_train + n_val]
    test = videos[n_train + n_val:]
    return train, val, test


def process_video(
    video_path: Path,
    output_dir: Path,
    sample_fps: float,
    blur_threshold: float,
    duplicate_threshold: float,
    max_side: int | None,
    jpeg_quality: int,
):
    """
    Extract frames from a single video, skipping blurry and near-duplicate frames.
    Duplicate detection is only within the current video.
    """
    cap = cv2.VideoCapture(str(video_path))
    if not cap.isOpened():
        print(f"[WARN] Could not open video: {video_path}")
        return {
            "saved": 0,
            "blurry_skipped": 0,
            "duplicate_skipped": 0,
            "read_frames": 0,
            "sampled_frames": 0,
        }

    src_fps = cap.get(cv2.CAP_PROP_FPS)
    if src_fps is None or src_fps <= 0 or np.isnan(src_fps):
        src_fps = 30.0

    if sample_fps <= 0:
        frame_interval = 1
    else:
        frame_interval = max(1, int(round(src_fps / sample_fps)))

    video_stem = video_path.stem
    read_frames = 0
    sampled_frames = 0
    saved_count = 0
    blurry_skipped = 0
    dup_skipped = 0
    last_kept_thumb = None

    ensure_dir(output_dir)

    while True:
        ret, frame = cap.read()
        if not ret:
            break

        current_idx = read_frames
        read_frames += 1

        if current_idx % frame_interval != 0:
            continue

        sampled_frames += 1
        frame = resize_if_needed(frame, max_side)

        blur_score = laplacian_variance(frame)
        if blur_score < blur_threshold:
            blurry_skipped += 1
            continue

        thumb = make_thumb(frame)
        if last_kept_thumb is not None:
            diff = mean_abs_diff(thumb, last_kept_thumb)
            if diff < duplicate_threshold:
                dup_skipped += 1
                continue

        out_name = f"{video_stem}_{saved_count:06d}.jpg"
        out_path = output_dir / out_name

        ok = cv2.imwrite(
            str(out_path),
            frame,
            [cv2.IMWRITE_JPEG_QUALITY, jpeg_quality],
        )
        if not ok:
            print(f"[WARN] Failed to write image: {out_path}")
            continue

        last_kept_thumb = thumb
        saved_count += 1

    cap.release()

    return {
        "saved": saved_count,
        "blurry_skipped": blurry_skipped,
        "duplicate_skipped": dup_skipped,
        "read_frames": read_frames,
        "sampled_frames": sampled_frames,
    }


def build_dataset(
    input_root: Path,
    output_root: Path,
    sample_fps: float,
    blur_threshold: float,
    duplicate_threshold: float,
    max_side: int | None,
    jpeg_quality: int,
    train_ratio: float,
    val_ratio: float,
    seed: int,
):
    ensure_dir(output_root)
    ensure_dir(output_root / "train")
    ensure_dir(output_root / "val")
    ensure_dir(output_root / "test")

    summary_rows = []

    class_dirs = sorted([p for p in input_root.iterdir() if p.is_dir()])
    if not class_dirs:
        print(f"[ERROR] No class folders found in: {input_root}")
        return

    for class_dir in class_dirs:
        class_name = class_dir.name
        videos = sorted([p for p in class_dir.iterdir() if p.is_file() and is_video_file(p)])

        if not videos:
            print(f"[INFO] No videos found in class folder: {class_name}")
            continue

        train_videos, val_videos, test_videos = split_videos(
            videos,
            train_ratio=train_ratio,
            val_ratio=val_ratio,
            seed=seed,
        )

        split_map = {}
        for p in train_videos:
            split_map[p] = "train"
        for p in val_videos:
            split_map[p] = "val"
        for p in test_videos:
            split_map[p] = "test"

        print(f"\n[CLASS] {class_name}")
        print(f"  Videos: {len(videos)}")
        print(f"  Train: {len(train_videos)} | Val: {len(val_videos)} | Test: {len(test_videos)}")

        for video_path in videos:
            split = split_map[video_path]
            out_dir = output_root / split / class_name

            stats = process_video(
                video_path=video_path,
                output_dir=out_dir,
                sample_fps=sample_fps,
                blur_threshold=blur_threshold,
                duplicate_threshold=duplicate_threshold,
                max_side=max_side,
                jpeg_quality=jpeg_quality,
            )

            print(
                f"    [{split.upper()}] {video_path.name} -> "
                f"saved={stats['saved']} "
                f"blurry_skipped={stats['blurry_skipped']} "
                f"duplicate_skipped={stats['duplicate_skipped']}"
            )

            summary_rows.append({
                "class_name": class_name,
                "video_name": video_path.name,
                "split": split,
                "read_frames": stats["read_frames"],
                "sampled_frames": stats["sampled_frames"],
                "saved_frames": stats["saved"],
                "blurry_skipped": stats["blurry_skipped"],
                "duplicate_skipped": stats["duplicate_skipped"],
            })

    summary_csv = output_root / "split_summary.csv"
    with open(summary_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(
            f,
            fieldnames=[
                "class_name",
                "video_name",
                "split",
                "read_frames",
                "sampled_frames",
                "saved_frames",
                "blurry_skipped",
                "duplicate_skipped",
            ],
        )
        writer.writeheader()
        writer.writerows(summary_rows)

    print(f"\nDone. Summary written to: {summary_csv}")


def main():
    parser = argparse.ArgumentParser(
        description="Extract, clean, and split video frames into train/val/test folders."
    )
    parser.add_argument(
        "--input_root",
        required=True,
        help="Root folder containing class folders, each with videos inside.",
    )
    parser.add_argument(
        "--output_root",
        required=True,
        help="Root output folder for dataset/train, dataset/val, dataset/test.",
    )
    parser.add_argument(
        "--sample_fps",
        type=float,
        default=2.0,
        help="Frames per second to sample from each video. Default: 2.0",
    )
    parser.add_argument(
        "--blur_threshold",
        type=float,
        default=80.0,
        help="Lower keeps more blurry frames. Default: 80.0",
    )
    parser.add_argument(
        "--duplicate_threshold",
        type=float,
        default=6.0,
        help="Lower is stricter duplicate removal. Default: 6.0",
    )
    parser.add_argument(
        "--max_side",
        type=int,
        default=1280,
        help="Resize images so longest side is this value. Use 0 to disable. Default: 1280",
    )
    parser.add_argument(
        "--jpeg_quality",
        type=int,
        default=95,
        help="JPEG quality from 0-100. Default: 95",
    )
    parser.add_argument(
        "--train_ratio",
        type=float,
        default=0.7,
        help="Train split ratio for classes with 4+ videos. Default: 0.7",
    )
    parser.add_argument(
        "--val_ratio",
        type=float,
        default=0.15,
        help="Validation split ratio for classes with 4+ videos. Default: 0.15",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="Random seed for per-class video shuffling. Default: 42",
    )

    args = parser.parse_args()

    input_root = Path(args.input_root)
    output_root = Path(args.output_root)

    if not input_root.exists():
        raise FileNotFoundError(f"Input folder does not exist: {input_root}")

    build_dataset(
        input_root=input_root,
        output_root=output_root,
        sample_fps=args.sample_fps,
        blur_threshold=args.blur_threshold,
        duplicate_threshold=args.duplicate_threshold,
        max_side=args.max_side,
        jpeg_quality=args.jpeg_quality,
        train_ratio=args.train_ratio,
        val_ratio=args.val_ratio,
        seed=args.seed,
    )


if __name__ == "__main__":
    main()